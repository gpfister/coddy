"""Rich UI elements and renderables for live and completed agent execution views."""

from __future__ import annotations

import time
from dataclasses import dataclass, field
from typing import Any

from rich import box
from rich.console import Group, RenderableType
from rich.markup import escape
from rich.table import Table
from rich.text import Text

from app.coddy.utils.ui.cost_formatter import format_cost_eur
from app.coddy.utils.ui.duration_formatter import format_duration


@dataclass
class PromptProcessingActivity:
    """Represents a completed LLM prompt processing phase (TTFT)."""

    duration_sec: float = 0.0


@dataclass
class ThinkingActivity:
    """Represents a completed LLM reasoning / thinking turn."""

    duration_sec: float = 0.0
    reasoning_tokens: int = 0


@dataclass
class OutputGenerationActivity:
    """Represents a completed LLM output generation phase."""

    duration_sec: float = 0.0
    completion_tokens: int = 0
    tokens_per_sec: float | None = None


@dataclass
class ToolCallActivity:
    """Represents an executed tool call."""

    tool_name: str
    status: str = "SUCCESS"  # SUCCESS or FAILED
    duration_sec: float = 0.0
    error_message: str | None = None


@dataclass
class UserQuestionActivity:
    """Represents a clarification question asked to the user and their response."""

    question: str
    options: list[str] = field(default_factory=list)
    selected_idx: int = 1
    custom_answer: str | None = None


@dataclass
class IntermediateTextActivity:
    """Represents intermediate non-artifact text generated by the agent."""

    text: str


@dataclass
class ArtifactActivity:
    """Represents a generated artifact file."""

    name: str
    path: str


ActivityItem = (
    PromptProcessingActivity
    | ThinkingActivity
    | OutputGenerationActivity
    | ToolCallActivity
    | UserQuestionActivity
    | IntermediateTextActivity
    | ArtifactActivity
)


@dataclass
class AgentMetrics:
    """Metrics summary for an agent's run."""

    turns: int = 0
    prompt_tokens: int = 0
    completion_tokens: int = 0
    reasoning_tokens: int = 0
    cached_tokens: int = 0
    duration_sec: float = 0.0
    cost_eur: float = 0.0


class AgentExecutionView:
    """Rich renderable managing live and completed views of agent execution."""

    def __init__(self, agent_name: str) -> None:
        self.agent_name = agent_name
        self.status = "running"  # "running", "completed", "failed"
        self.activities: list[ActivityItem] = []
        self.active_operation: str | None = None  # e.g. "thinking" or "tool:<tool_name>"
        self.metrics: AgentMetrics | None = None
        self.start_time: float = time.perf_counter()

    def add_prompt_processing(self, duration_sec: float) -> None:
        """Records a completed prompt processing turn (TTFT)."""
        self.activities.append(PromptProcessingActivity(duration_sec=duration_sec))

    def add_thinking(self, duration_sec: float, reasoning_tokens: int = 0) -> None:
        """Records a completed thinking turn."""
        self.activities.append(ThinkingActivity(duration_sec=duration_sec, reasoning_tokens=reasoning_tokens))

    def add_output_generation(
        self,
        duration_sec: float,
        completion_tokens: int = 0,
        tokens_per_sec: float | None = None,
    ) -> None:
        """Records a completed output generation turn."""
        self.activities.append(
            OutputGenerationActivity(
                duration_sec=duration_sec,
                completion_tokens=completion_tokens,
                tokens_per_sec=tokens_per_sec,
            )
        )

    def add_tool_call(
        self,
        tool_name: str,
        status: str,
        duration_sec: float,
        error_message: str | None = None,
    ) -> None:
        """Records a completed tool execution."""
        self.activities.append(
            ToolCallActivity(
                tool_name=tool_name,
                status=status,
                duration_sec=duration_sec,
                error_message=error_message,
            )
        )

    def add_user_question(
        self,
        question: str,
        options: list[str],
        selected_idx: int = 1,
        custom_answer: str | None = None,
    ) -> None:
        """Records an interactive question asked to the user and their response."""
        self.activities.append(
            UserQuestionActivity(
                question=question,
                options=list(options),
                selected_idx=selected_idx,
                custom_answer=custom_answer,
            )
        )

    def add_intermediate_text(self, text: str) -> None:
        """Records intermediate text output from the agent."""
        self.activities.append(IntermediateTextActivity(text=text))

    def add_artifact(self, name: str, path: str) -> None:
        """Records an artifact generated during execution."""
        self.activities.append(ArtifactActivity(name=name, path=path))

    def set_active_operation(self, op: str | None) -> None:
        """Sets the currently running sub-operation (e.g. 'thinking' or 'tool:<name>')."""
        self.active_operation = op

    def complete(self, metrics: AgentMetrics | dict[str, Any] | None = None) -> None:
        """Marks the agent view as completed with optional metrics."""
        self.status = "completed"
        self.active_operation = None
        if isinstance(metrics, dict):
            self.metrics = AgentMetrics(**metrics)
        elif isinstance(metrics, AgentMetrics):
            self.metrics = metrics
        elif self.metrics is None:
            # Fallback duration if not provided
            self.metrics = AgentMetrics(duration_sec=max(0.0, time.perf_counter() - self.start_time))

    def fail(self, error_message: str | None = None) -> None:
        """Marks the agent view as failed."""
        self.status = "failed"
        self.active_operation = None

    def __rich__(self) -> RenderableType:
        renderables: list[RenderableType] = []

        # 1. Header: Plain yellow circle in front of agent
        if self.status == "running":
            renderables.append(
                Text.from_markup(f"[bold yellow]●[/bold yellow] [bold]{escape(self.agent_name)}[/bold] is running")
            )
        elif self.status == "completed":
            renderables.append(
                Text.from_markup(f"[bold yellow]●[/bold yellow] [bold]{escape(self.agent_name)}[/bold] has run")
            )
        else:
            renderables.append(
                Text.from_markup(f"[bold red]●[/bold red] [bold]{escape(self.agent_name)}[/bold] failed")
            )

        # 2. Activity Items
        for item in self.activities:
            if isinstance(item, PromptProcessingActivity):
                dur_str = format_duration(item.duration_sec)
                renderables.append(Text.from_markup(f"  [bold green]✔[/bold green] Processed prompt for {dur_str}"))

            elif isinstance(item, ThinkingActivity):
                dur_str = format_duration(item.duration_sec)
                renderables.append(Text.from_markup(f"  [bold green]✔[/bold green] Thought for {dur_str}"))

            elif isinstance(item, OutputGenerationActivity):
                dur_str = format_duration(item.duration_sec)
                renderables.append(Text.from_markup(f"  [bold green]✔[/bold green] Output generated for {dur_str}"))

            elif isinstance(item, ToolCallActivity):
                dur_str = format_duration(item.duration_sec)
                t_name = escape(item.tool_name)
                if item.status == "SUCCESS":
                    renderables.append(
                        Text.from_markup(
                            f"  [bold green]✔[/bold green] Successfully called tool [bold]{t_name}[/bold] (duration {dur_str})"
                        )
                    )
                else:
                    renderables.append(
                        Text.from_markup(
                            f"  [bold red]✖[/bold red] Failed calling tool [bold]{t_name}[/bold] (duration {dur_str})"
                        )
                    )

            elif isinstance(item, UserQuestionActivity):
                renderables.append(Text.from_markup("  [bold green]✔[/bold green] Asked question to user"))
                renderables.append(Text.from_markup(f"  | Question: {escape(item.question)}"))
                total_opts = len(item.options)
                for idx, opt in enumerate(item.options, 1):
                    opt_escaped = escape(opt)
                    if idx == item.selected_idx:
                        renderables.append(Text.from_markup(f"  |   --> {idx}. {opt_escaped}"))
                    else:
                        renderables.append(Text.from_markup(f"  |       {idx}. {opt_escaped}"))

                custom_idx = total_opts + 1
                if item.custom_answer is not None and item.selected_idx == custom_idx:
                    custom_escaped = escape(item.custom_answer)
                    renderables.append(Text.from_markup(f"  |   --> {custom_idx}. Custom response: {custom_escaped}"))
                else:
                    renderables.append(Text.from_markup(f"  |       {custom_idx}. Custom response"))

            elif isinstance(item, IntermediateTextActivity):
                # Thought process / intermediate text is suppressed per specification
                pass

            elif isinstance(item, ArtifactActivity):
                art_name = escape(item.name)
                art_path = escape(item.path)
                renderables.append(
                    Text.from_markup(
                        f"  [bold green]✔[/bold green] Generated artifact [bold cyan underline link=file://{art_path}]{art_name}[/bold cyan underline link]"
                    )
                )

        # 3. Active in-progress operation
        if self.status == "running":
            if self.active_operation == "processing":
                renderables.append(Text.from_markup("  [bold yellow]●[/bold yellow] Processing prompt..."))
            elif self.active_operation == "thinking":
                renderables.append(Text.from_markup("  [bold yellow]●[/bold yellow] Thinking..."))
            elif self.active_operation == "generating":
                renderables.append(Text.from_markup("  [bold yellow]●[/bold yellow] Generating output..."))
            elif self.active_operation and self.active_operation.startswith("tool:"):
                tool_name = escape(self.active_operation.split(":", 1)[1])
                renderables.append(
                    Text.from_markup(f"  [bold yellow]●[/bold yellow] Calling tool [bold]{tool_name}[/bold]...")
                )

        # 4. Completed Agent Metrics Table
        if self.status == "completed" and self.metrics is not None:
            renderables.append(Text(""))
            table = Table(
                title=None,
                box=box.ROUNDED,
                header_style="bold cyan",
                show_header=True,
                pad_edge=False,
                collapse_padding=True,
            )
            table.add_column("Agent", style="bold")
            table.add_column("Turns", justify="right")
            table.add_column("Prompt Tokens", justify="right")
            table.add_column("Completion Tokens", justify="right")
            table.add_column("Reasoning Tokens", justify="right")
            table.add_column("Cached Tokens", justify="right")
            table.add_column("Duration", justify="right", style="green")
            table.add_column("Cost (EUR)", justify="right", style="bold yellow")

            dur_str = format_duration(self.metrics.duration_sec)
            cost_str = format_cost_eur(self.metrics.cost_eur)
            table.add_row(
                self.agent_name,
                str(self.metrics.turns),
                f"{self.metrics.prompt_tokens:,}",
                f"{self.metrics.completion_tokens:,}",
                f"{self.metrics.reasoning_tokens:,}",
                f"{self.metrics.cached_tokens:,}",
                dur_str,
                cost_str,
            )
            renderables.append(table)

        return Group(*renderables)
