"""Strict Pydantic v2 schema for coding-research-plan structured output."""

from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, Field, field_validator


def _check_placeholder(v: str, field_name: str) -> str:
    if v and v.strip().lower() in {"...", "todo", "tbd", "fixme", "placeholder", "n/a"}:
        raise ValueError(f"{field_name} cannot be a placeholder ('{v}')")
    return v


class ResearchPlanApproach(BaseModel):
    """Specific technical approach, pattern, or angle to explore for a research subject."""

    model_config = ConfigDict(extra="forbid")

    name: str = Field(description="Name or title of the technical approach.")
    description: str = Field(description="Description of how this technical approach works.")
    rationale: str = Field(description="Rationale, benefits, trade-offs, or criteria for evaluation.")

    @field_validator("name")
    @classmethod
    def validate_name_not_placeholder(cls, v: str) -> str:
        return _check_placeholder(v, "name")


class ResearchPlanSubject(BaseModel):
    """A granular subject to be researched under an architectural topic."""

    model_config = ConfigDict(extra="forbid")

    title: str = Field(description="Title of the research subject.")
    description: str = Field(description="Detailed technical question, objectives, or aspects to investigate.")
    target_sources: list[Literal["code", "document", "web"]] = Field(
        default_factory=lambda: ["code", "document"],
        description="Target research channels to query (code, document, and/or web).",
    )
    open_issues: list[str] = Field(
        default_factory=list,
        description="List of concrete open issues, technical uncertainties, or questions this subject is expected to resolve.",
    )
    approaches: list[ResearchPlanApproach] = Field(
        default_factory=list,
        description="Specific technical approaches, patterns, or candidate options to evaluate.",
    )
    directions: list[str] = Field(
        default_factory=list,
        description="Markdown instructions directing what to research and expected deliverables (e.g. process flowchart, call sequence diagram, pros/cons table, alternatives, API documentation, FACT/INTENT/UNKNOWNS depth, target trust score).",
    )

    @field_validator("title")
    @classmethod
    def validate_title_not_placeholder(cls, v: str) -> str:
        return _check_placeholder(v, "title")

    @field_validator("open_issues")
    @classmethod
    def validate_open_issues_not_placeholder(cls, v: list[str]) -> list[str]:
        for item in v:
            _check_placeholder(item, "open_issues")
        return v


class ResearchPlanTopic(BaseModel):
    """An architectural topic grouping related research subjects."""

    model_config = ConfigDict(extra="forbid")

    topic: str = Field(
        description="Name of the architectural topic or subsystem group (e.g. 'Authentication', 'Data Persistence')."
    )
    description: str = Field(
        default="",
        description="High-level technical context explaining why this topic requires research and investigation.",
    )
    subjects: list[ResearchPlanSubject] = Field(
        default_factory=list,
        description="List of specific research subjects grouped under this topic.",
    )

    @field_validator("topic")
    @classmethod
    def validate_topic_not_placeholder(cls, v: str) -> str:
        return _check_placeholder(v, "topic")


class ResearchMaterialAssessment(BaseModel):
    """Assessment of a research material file ingested for context."""

    model_config = ConfigDict(extra="forbid")

    file_path: str = Field(description="Path or identifier of the research material file.")
    served_information: str = Field(description="Information, requirements, or architecture served by this file.")
    investigation_targets: str = Field(
        description="Specific aspects to investigate in repository code or documentation based on this material."
    )
    requires_internet_research: bool = Field(
        description="Whether subsequent external web research must be performed for topics arising from this material."
    )
    internet_research_rationale: str = Field(
        default="",
        description="Rationale or description of what external internet research must be conducted.",
    )

    @field_validator("file_path", "served_information", "investigation_targets")
    @classmethod
    def validate_not_placeholder(cls, v: str, info) -> str:
        return _check_placeholder(v, info.field_name)


class ResearchPlan(BaseModel):
    """Structured research plan generated by coding-research-plan."""

    model_config = ConfigDict(extra="forbid")

    rationale: str = Field(
        default="",
        description="High-level reasoning explaining how the user request and architecture instructions were broken down.",
    )
    user_request_summary: str = Field(
        default="",
        description="1-paragraph summary of the user request for episodic research context.",
    )
    user_request_bullets: list[str] = Field(
        default_factory=list,
        description="5 to 10 bullet points summarizing key aspects and requirements of the user request.",
    )
    project_context_summary: str = Field(
        default="",
        description="1-paragraph summary of the project architecture and purpose.",
    )
    project_context_bullets: list[str] = Field(
        default_factory=list,
        description="5 to 10 bullet points summarizing key architectural invariants and project context.",
    )
    topics: list[ResearchPlanTopic] = Field(
        default_factory=list,
        description="List of architectural and technical topics, each containing specific research subjects.",
    )
    research_materials: list[ResearchMaterialAssessment] = Field(
        default_factory=list,
        description="Assessment of how ingested research material files serve the plan and drive code/web research.",
    )

    @field_validator("rationale")
    @classmethod
    def validate_rationale_not_placeholder(cls, v: str) -> str:
        return _check_placeholder(v, "rationale")


def normalize_research_plan_data(data: Any) -> dict[str, Any]:
    """Normalizes raw dictionary from LLM into a structure conforming to ResearchPlan.

    Resiliently handles key synonyms ('name' -> 'topic', 'items' -> 'subjects', string lists).
    """
    if not isinstance(data, dict):
        return {
            "rationale": str(data) if data is not None else "",
            "topics": [],
        }

    rationale = data.get("rationale") or data.get("reasoning") or data.get("summary") or data.get("analysis") or ""

    if rationale and rationale.strip().lower() in {"...", "todo", "tbd", "fixme", "placeholder", "n/a"}:
        rationale = ""

    raw_topics = (
        data.get("topics")
        or data.get("research_topics")
        or data.get("subjects_by_topic")
        or data.get("groups")
        or data.get("items")
        or []
    )

    valid_sources = {"code", "document", "web"}
    normalized_topics: list[dict[str, Any]] = []

    if isinstance(raw_topics, list):
        for t_idx, item in enumerate(raw_topics, start=1):
            if isinstance(item, str):
                t_str = item.strip()
                if t_str.lower() in {"...", "todo", "tbd", "fixme", "placeholder", "n/a"}:
                    t_str = f"Topic {t_idx}"
                normalized_topics.append(
                    {
                        "topic": t_str,
                        "description": f"Research topic for {t_str}",
                        "subjects": [
                            {
                                "title": t_str,
                                "description": f"Investigate implementation details for {t_str}",
                                "target_sources": ["code", "document"],
                                "approaches": [],
                            }
                        ],
                    }
                )
            elif isinstance(item, dict):
                t_name = (
                    item.get("topic") or item.get("name") or item.get("title") or item.get("group") or f"Topic {t_idx}"
                )
                if str(t_name).strip().lower() in {"...", "todo", "tbd", "fixme", "placeholder", "n/a"}:
                    t_name = f"Topic {t_idx}"
                t_desc = item.get("description") or item.get("context") or ""

                raw_subjects = (
                    item.get("subjects") or item.get("items") or item.get("subtopics") or item.get("questions") or []
                )

                normalized_subjects: list[dict[str, Any]] = []
                if isinstance(raw_subjects, list):
                    for s_idx, s_item in enumerate(raw_subjects, start=1):
                        if isinstance(s_item, str):
                            s_str = s_item.strip()
                            if s_str.lower() in {"...", "todo", "tbd", "fixme", "placeholder", "n/a"}:
                                s_str = f"Subject {s_idx}"
                            normalized_subjects.append(
                                {
                                    "title": s_str,
                                    "description": f"Investigate {s_str}",
                                    "target_sources": ["code", "document"],
                                    "approaches": [],
                                }
                            )
                        elif isinstance(s_item, dict):
                            s_title = (
                                s_item.get("title") or s_item.get("subject") or s_item.get("name") or f"Subject {s_idx}"
                            )
                            if str(s_title).strip().lower() in {"...", "todo", "tbd", "fixme", "placeholder", "n/a"}:
                                s_title = f"Subject {s_idx}"
                            s_desc = (
                                s_item.get("description")
                                or s_item.get("details")
                                or s_item.get("objective")
                                or f"Investigate {s_title}"
                            )

                            # Sources normalization
                            raw_sources = s_item.get("target_sources") or s_item.get("sources") or ["code", "document"]
                            if isinstance(raw_sources, str):
                                raw_sources = [s.strip().lower() for s in raw_sources.split(",")]
                            sources = [s.lower() for s in raw_sources if s.lower() in valid_sources]
                            if not sources:
                                sources = ["code", "document"]

                            # Open issues normalization
                            raw_open_issues = (
                                s_item.get("open_issues")
                                or s_item.get("issues")
                                or s_item.get("open_questions")
                                or s_item.get("questions")
                                or []
                            )
                            normalized_open_issues: list[str] = []
                            if isinstance(raw_open_issues, list):
                                for o_item in raw_open_issues:
                                    if isinstance(o_item, str) and o_item.strip():
                                        if o_item.strip().lower() not in {
                                            "...",
                                            "todo",
                                            "tbd",
                                            "fixme",
                                            "placeholder",
                                            "n/a",
                                        }:
                                            normalized_open_issues.append(o_item.strip())
                                    elif isinstance(o_item, dict):
                                        issue_text = (
                                            o_item.get("issue")
                                            or o_item.get("title")
                                            or o_item.get("description")
                                            or str(o_item)
                                        )
                                        if issue_text.strip() and issue_text.strip().lower() not in {
                                            "...",
                                            "todo",
                                            "tbd",
                                            "fixme",
                                            "placeholder",
                                            "n/a",
                                        }:
                                            normalized_open_issues.append(issue_text.strip())
                            elif isinstance(raw_open_issues, str) and raw_open_issues.strip():
                                if raw_open_issues.strip().lower() not in {
                                    "...",
                                    "todo",
                                    "tbd",
                                    "fixme",
                                    "placeholder",
                                    "n/a",
                                }:
                                    normalized_open_issues = [raw_open_issues.strip()]

                            # Approaches normalization
                            raw_approaches = s_item.get("approaches") or s_item.get("options") or []
                            normalized_approaches: list[dict[str, Any]] = []
                            if isinstance(raw_approaches, list):
                                for a_idx, a_item in enumerate(raw_approaches, start=1):
                                    if isinstance(a_item, str):
                                        a_str = a_item.strip()
                                        if a_str.lower() in {"...", "todo", "tbd", "fixme", "placeholder", "n/a"}:
                                            a_str = f"Approach {a_idx}"
                                        normalized_approaches.append(
                                            {
                                                "name": a_str,
                                                "description": f"Explore approach: {a_str}",
                                                "rationale": "Standard engineering candidate approach",
                                            }
                                        )
                                    elif isinstance(a_item, dict):
                                        app_name = str(
                                            a_item.get("name") or a_item.get("title") or f"Approach {a_idx}"
                                        ).strip()
                                        if app_name.lower() in {"...", "todo", "tbd", "fixme", "placeholder", "n/a"}:
                                            app_name = f"Approach {a_idx}"
                                        normalized_approaches.append(
                                            {
                                                "name": app_name,
                                                "description": str(
                                                    a_item.get("description") or a_item.get("details") or ""
                                                ),
                                                "rationale": str(
                                                    a_item.get("rationale")
                                                    or a_item.get("tradeoffs")
                                                    or "Evaluated candidate"
                                                ),
                                            }
                                        )

                            normalized_subjects.append(
                                {
                                    "title": str(s_title).strip(),
                                    "description": str(s_desc).strip(),
                                    "target_sources": sources,
                                    "open_issues": normalized_open_issues,
                                    "approaches": normalized_approaches,
                                    "directions": [
                                        str(d).strip()
                                        for d in (s_item.get("directions") or s_item.get("expected_outputs") or [])
                                        if str(d).strip()
                                    ],
                                }
                            )

                normalized_topics.append(
                    {
                        "topic": str(t_name).strip(),
                        "description": str(t_desc).strip(),
                        "subjects": normalized_subjects,
                    }
                )

    raw_materials = data.get("research_materials") or data.get("materials") or []
    normalized_materials: list[dict[str, Any]] = []
    if isinstance(raw_materials, list):
        for m_item in raw_materials:
            if isinstance(m_item, dict):
                f_path = str(m_item.get("file_path") or m_item.get("path") or m_item.get("file") or "").strip()
                s_info = str(
                    m_item.get("served_information") or m_item.get("information") or m_item.get("summary") or ""
                ).strip()
                i_targets = str(
                    m_item.get("investigation_targets")
                    or m_item.get("targets")
                    or m_item.get("code_investigation")
                    or ""
                ).strip()
                req_net = bool(m_item.get("requires_internet_research") or m_item.get("requires_web_research") or False)
                net_rat = str(m_item.get("internet_research_rationale") or m_item.get("web_rationale") or "").strip()
                if f_path and s_info and i_targets:
                    normalized_materials.append(
                        {
                            "file_path": f_path,
                            "served_information": s_info,
                            "investigation_targets": i_targets,
                            "requires_internet_research": req_net,
                            "internet_research_rationale": net_rat,
                        }
                    )

    u_summary = str(data.get("user_request_summary") or "").strip()
    u_bullets = [str(b).strip() for b in (data.get("user_request_bullets") or []) if str(b).strip()]
    p_summary = str(data.get("project_context_summary") or "").strip()
    p_bullets = [str(b).strip() for b in (data.get("project_context_bullets") or []) if str(b).strip()]

    return {
        "rationale": str(rationale).strip(),
        "user_request_summary": u_summary,
        "user_request_bullets": u_bullets,
        "project_context_summary": p_summary,
        "project_context_bullets": p_bullets,
        "topics": normalized_topics,
        "research_materials": normalized_materials,
    }
